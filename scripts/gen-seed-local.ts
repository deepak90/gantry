/**
 * Writes supabase/seed_local.sql (gitignored) with machine-specific demo values that must not live
 * in the committed seed: who the rentals pay and who Harbor bills, in the PayPal sandbox.
 *
 * Each rental supplier is paid to its own sandbox account when there is one,
 * PAYPAL_SANDBOX_<first word of its name>_EMAIL (PAYPAL_SANDBOX_NORTHGATE_EMAIL for Northgate Equipment Rental), and to
 * PAYPAL_SANDBOX_PAYEE_EMAIL otherwise. The payout functions refuse a payout into an account that is set up for anyone
 * else (supabase/functions/_shared/accounts.ts), so this warns when the catch-all payee is also a party's own account.
 *
 * `pnpm db:reset` runs it first; `supabase db reset` loads it after seed.sql and seed_snapshot.sql (see supabase/config.toml).
 * The same file can be applied to the hosted project's database to point its copies at the same accounts.
 * Without PAYPAL_SANDBOX_PAYEE_EMAIL the file is removed and the seed placeholder stays.
 */
import { existsSync, unlinkSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { sandboxAccounts } from '../supabase/functions/_shared/accounts.ts';

const target = fileURLToPath(new URL('../supabase/seed_local.sql', import.meta.url));
const payee = process.env.PAYPAL_SANDBOX_PAYEE_EMAIL?.trim();
/** The tenant's own sandbox account, if it has one: the invoices of Harbor and of its copies bill it. */
const tenant = process.env.PAYPAL_SANDBOX_TENANT_EMAIL?.trim() || payee;
const EMAIL = /^[^\s'@]+@[^\s']+\.[^\s']+$/;
/** The parties whose accounts are never a rental supplier's: the tenant, and the general contractor who pays. */
const NOT_SUPPLIERS = new Set(['PAYEE', 'TENANT', 'GC']);

/** Each firm's own account, by the first word of its name, as set in the environment. */
const own = Object.entries(process.env)
  .map(([key, value]) => [/^PAYPAL_SANDBOX_([A-Z0-9]+)_EMAIL$/.exec(key)?.[1], value?.trim()] as const)
  .filter((entry): entry is readonly [string, string] => Boolean(entry[0]) && !NOT_SUPPLIERS.has(entry[0]!) && EMAIL.test(entry[1] ?? ''));

if (!payee) {
  if (existsSync(target)) unlinkSync(target);
  console.log('PAYPAL_SANDBOX_PAYEE_EMAIL not set; no local seed overlay');
} else if (!EMAIL.test(payee) || !EMAIL.test(tenant ?? '')) {
  console.error('PAYPAL_SANDBOX_PAYEE_EMAIL or PAYPAL_SANDBOX_TENANT_EMAIL is not an email address.');
  process.exit(1);
} else {
  const firstWord = `upper(regexp_replace(split_part(btrim(supplier_name), ' ', 1), '[^A-Za-z0-9]', '', 'g'))`;
  const payees =
    own.length === 0
      ? `'${payee}'`
      : `case ${firstWord}\n${own.map(([word, email]) => `    when '${word}' then '${email}'`).join('\n')}\n    else '${payee}'\n  end`;
  const sql = [
    '-- GENERATED by scripts/gen-seed-local.ts from .env.local; gitignored, machine-specific.',
    `update public.equipment_bookings set supplier_payout_email = ${payees};`,
    `update public.projects set client_email = '${tenant}' where template = 'harbor';`,
    '',
  ].join('\n');
  writeFileSync(target, sql);
  console.log(`wrote ${target}: a rental supplier with an account of its own is paid there (accounts set up: ${own.map(([word]) => word).join(', ') || 'none'}), any other PAYPAL_SANDBOX_PAYEE_EMAIL`);
  const shared = sandboxAccounts(process.env).alsoOf('PAYEE', payee);
  if (shared) console.warn(`PAYPAL_SANDBOX_PAYEE_EMAIL is also PAYPAL_SANDBOX_${shared}_EMAIL: a rental paid there is refused, so give each rental supplier an account of its own.`);
}
