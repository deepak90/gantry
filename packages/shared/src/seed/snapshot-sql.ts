/**
 * Renders supabase/seed_snapshot.sql: idempotent upserts of the seed projects (each with its Bryntum
 * inline data as the jsonb snapshot at revision 0) and their equipment bookings. A private copy of a
 * project for the hosted demo shares that project's snapshot and joins the pool of copies. Used by
 * scripts/gen-seed-snapshot.ts, which runs under Node's type stripping, so this file imports
 * types only.
 */
import type { SeedProject } from './index';

export interface SnapshotSqlInput {
  project: SeedProject;
  /** The booking id is needed when the project has a booking. */
  ids: { readonly project: string; readonly booking?: string };
  /** The starter library as `seed_library()` takes it (library-starter.ts `starterLibrarySeed()`). */
  library: unknown[];
}

const GENERATED_HEADER =
  '-- GENERATED by scripts/gen-seed-snapshot.ts from packages/shared/src/seed — do not edit by hand.';

/** Dollar-quote tags for the snapshot and the library; the renderer refuses data that contains them. */
const SNAPSHOT_TAG = '$snapshot$';
const LIBRARY_TAG = '$library$';

const BOOKING_COLUMNS = [
  'id',
  'project_id',
  'task_id',
  'resource_id',
  'supplier_name',
  'supplier_payout_email',
  'rental_rate_minor',
  'currency',
  'billable_start',
  'billable_end',
  'idle_days',
  'evidence_path',
] as const;

/** Recursively sorts object keys so the generated file is stable across refactors of the seed. */
export function canonicalJson(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(canonicalJson);
  if (value !== null && typeof value === 'object') {
    const source = value as Record<string, unknown>;
    const sorted: Record<string, unknown> = {};
    for (const key of Object.keys(source).sort()) sorted[key] = canonicalJson(source[key]);
    return sorted;
  }
  return value;
}

export function sqlLiteral(value: string | number | null): string {
  if (value === null) return 'null';
  if (typeof value === 'number') {
    if (!Number.isFinite(value)) throw new Error(`Not a finite number: ${value}`);
    return String(value);
  }
  return `'${value.replace(/'/g, "''")}'`;
}

/**
 * Every project, one after the other, under one header. A copy (`copyOf`) comes after the project it copies and
 * takes that project's seed plan from its demo_seeds row instead of repeating it.
 */
export function renderSeedSnapshotsSql(inputs: readonly SnapshotSqlInput[]): string {
  return [GENERATED_HEADER, '-- Regenerate with: pnpm seed:snapshot', '', ...inputs.flatMap((input, index) => projectLines(input, inputs.slice(0, index)))].join('\n');
}

/** The snapshot as a jsonb literal, or, for a copy, the seed plan of the project it copies (rendered earlier). */
function snapshotSql(project: SeedProject, before: readonly SnapshotSqlInput[]): string {
  const snapshot = JSON.stringify(canonicalJson(project.inlineData), null, 2);
  if (project.copyOf === undefined) {
    if (snapshot.includes(SNAPSHOT_TAG)) {
      throw new Error(`Snapshot JSON contains the dollar-quote tag ${SNAPSHOT_TAG}`);
    }
    return `${SNAPSHOT_TAG}${snapshot}${SNAPSHOT_TAG}::jsonb`;
  }
  const source = before.find(({ ids }) => ids.project === project.copyOf);
  if (!source || source.project.copyOf !== undefined) {
    throw new Error(`${project.name}: the project it copies (${project.copyOf}) must be an original rendered before it`);
  }
  if (JSON.stringify(canonicalJson(source.project.inlineData), null, 2) !== snapshot) {
    throw new Error(`${project.name}: a copy must have the plan of the project it copies (${project.copyOf})`);
  }
  return `(select d.snapshot from public.demo_seeds d where d.project_id = ${sqlLiteral(project.copyOf)})`;
}

function projectLines({ project, ids, library }: SnapshotSqlInput, before: readonly SnapshotSqlInput[]): string[] {
  const libraryJson = JSON.stringify(canonicalJson(library), null, 2);
  if (libraryJson.includes(LIBRARY_TAG)) {
    throw new Error(`Library JSON contains the dollar-quote tag ${LIBRARY_TAG}`);
  }
  const lines = [
    ...(project.copyOf ? [`-- A private copy of ${project.name} for the hosted demo: its seed plan, its own rentals, a place in the pool of copies.`] : []),
    'insert into public.projects (id, name, currency, current_revision, snapshot, snapshot_revision, handover_task_id, listed, client_name, client_email, template) values (' +
      `${sqlLiteral(ids.project)}, ${sqlLiteral(project.name)}, ${sqlLiteral(project.currency)}, 0, ` +
      `${snapshotSql(project, before)}, 0, ${sqlLiteral(project.handover_task_id)}, ${project.unlisted ? 'false' : 'true'}, ` +
      `${sqlLiteral(project.client?.name ?? null)}, ${sqlLiteral(project.client?.email ?? null)}, ${sqlLiteral(project.template ?? null)})`,
    'on conflict (id) do update set name = excluded.name, currency = excluded.currency, snapshot = excluded.snapshot, snapshot_revision = excluded.snapshot_revision, handover_task_id = excluded.handover_task_id, listed = excluded.listed, client_name = excluded.client_name, client_email = excluded.client_email, template = excluded.template;',
    '',
  ];
  const booking = project.booking;
  if (booking && !ids.booking) throw new Error(`Project ${project.name} has a booking but no booking id`);
  const bookings = [...(booking ? [{ id: ids.booking!, ...booking }] : []), ...(project.moreBookings ?? [])];
  for (const row of bookings) {
    const bookingValues: Record<(typeof BOOKING_COLUMNS)[number], string | number | null> = {
      id: row.id,
      project_id: ids.project,
      task_id: row.task_id,
      resource_id: row.resource_id,
      supplier_name: row.supplier_name,
      supplier_payout_email: row.supplier_payout_email,
      rental_rate_minor: row.rental_rate_minor,
      currency: row.currency,
      billable_start: row.billable_start,
      billable_end: row.billable_end,
      idle_days: row.idle_days,
      evidence_path: row.evidence_path,
    };
    const updatedColumns = BOOKING_COLUMNS.filter((column) => column !== 'id');
    lines.push(
      `insert into public.equipment_bookings (${BOOKING_COLUMNS.join(', ')}) values (` +
        `${BOOKING_COLUMNS.map((column) => sqlLiteral(bookingValues[column])).join(', ')})`,
      `on conflict (id) do update set ${updatedColumns.map((column) => `${column} = excluded.${column}`).join(', ')};`,
      '',
    );
  }
  const seedBookings = `(select jsonb_agg(to_jsonb(all_b) order by all_b.id) from public.equipment_bookings all_b where all_b.project_id = p.id)`;
  lines.push(
    '-- What reset_demo() restores, the starter library (packages/shared/src/library-starter.ts) included.',
    'insert into public.demo_seeds (project_id, snapshot, booking, bookings, library)',
    booking
      ? `select p.id, p.snapshot, to_jsonb(b), ${seedBookings}, ${LIBRARY_TAG}${libraryJson}${LIBRARY_TAG}::jsonb from public.projects p join public.equipment_bookings b on b.id = ${sqlLiteral(ids.booking ?? null)} where p.id = ${sqlLiteral(ids.project)}`
      : `select p.id, p.snapshot, null, null, ${LIBRARY_TAG}${libraryJson}${LIBRARY_TAG}::jsonb from public.projects p where p.id = ${sqlLiteral(ids.project)}`,
    'on conflict (project_id) do update set snapshot = excluded.snapshot, booking = excluded.booking, bookings = excluded.bookings, library = excluded.library;',
    '',
    '-- The project starts with the starter library and the starter watch list.',
    `select public.seed_library(d.project_id, d.library) from public.demo_seeds d where d.project_id = ${sqlLiteral(ids.project)};`,
    `select public.seed_watch_rules(${sqlLiteral(ids.project)});`,
    '',
  );
  if (project.copyOf) {
    lines.push(
      '-- In the pool of copies, free until a visitor claims it (claim_copy); seeding again leaves a held copy held.',
      `insert into public.copy_pool (project_id) values (${sqlLiteral(ids.project)}) on conflict (project_id) do nothing;`,
      '',
    );
  }
  return lines;
}
